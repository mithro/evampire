"""Write the USB serial message sequence diagrams as Graphviz files.

Each diagram has two lanes, one per side, with time running downwards.
Every point is pinned, so neato draws the arrows level and evenly spaced.
Run with:

    uv run docs/usb-serial/sequences.py

SPDX-License-Identifier: Apache-2.0
"""

import pathlib

HERE = pathlib.Path(__file__).parent

STEP = 0.42          # vertical distance between rows, inches
COLOURS = {"host": "#dbe8f5", "device": "#fbe5d6"}


class Seq:
    def __init__(self, name, left, right, xl=1.2, xr=4.2, xn=6.0,
                 fill=("#dbe8f5", "#fbe5d6"), comment=""):
        self.name, self.comment = name, comment
        self.xl, self.xr, self.xn = xl, xr, xn
        self.y = 0.0
        self.n = 0
        self.lines = []
        self.heads = [(xl, left, fill[0]), (xr, right, fill[1])]

    def _pt(self, x, y):
        self.n += 1
        p = f"p{self.n}"
        self.lines.append(f'    {p} [pos="{x:.2f},{y:.2f}!"];')
        return p

    def _text(self, x, y, label, width, size=10, colour="#000000",
              bold=False):
        self.n += 1
        t = f"t{self.n}"
        font = ', fontname="Helvetica-Bold"' if bold else ""
        lines = label.count("\\n") + 1
        self.lines.append(
            f'    {t} [pos="{x:.2f},{y:.2f}!", shape=plaintext, '
            f'label="{label}", width={width}, height={0.17 * lines:.2f}, '
            f'fontsize={size}, fontcolor="{colour}"{font}];')

    def msg(self, frm, label, note="", colour="#000000", style="solid",
            lost=False):
        """A packet from 'l' or 'r' to the other lane."""
        self.y -= STEP
        y = self.y
        xa, xb = (self.xl, self.xr) if frm == "l" else (self.xr, self.xl)
        if lost:
            xm = (xa + xb) / 2
            a = self._pt(xa, y)
            b = self._pt(xm, y)
            self.lines.append(f'    {a} -> {b} [arrowhead=none, '
                              f'color="{colour}", style={style}];')
            self._text(xm + (0.12 if xb > xa else -0.12), y, "✕", 0.2,
                       size=12, colour="#c0392b")
        else:
            a = self._pt(xa, y)
            b = self._pt(xb, y)
            self.lines.append(f'    {a} -> {b} [color="{colour}", '
                              f'style={style}];')
        self._text((self.xl + self.xr) / 2, y + 0.13, label, 2.4,
                   colour=colour)
        if note:
            self._text(self.xn, y, note, 2.6, colour="#333333")

    def note(self, text, gap=1.0):
        self.y -= STEP * gap
        self._text(self.xn, self.y, text, 2.6, colour="#333333")

    def title(self, text):
        self.y -= STEP * 1.1
        self._text((self.xl + self.xr) / 2, self.y, text, 3.2, size=11,
                   colour="#1f4e79", bold=True)

    def action(self, side, text, gap=1.0):
        """A note beside one lane, for something done without a packet."""
        self.y -= STEP * gap
        x = self.xl - 0.15 if side == "l" else self.xr + 0.15
        self.n += 1
        t = f"t{self.n}"
        anchor_x = x - 0.8 if side == "l" else x + 0.8
        self.lines.append(
            f'    {t} [pos="{anchor_x:.2f},{self.y:.2f}!", shape=box, '
            f'style="rounded,filled", fillcolor="#f2f2f2", label="{text}", '
            f'width=1.5, height={0.18 * (text.count(chr(92) + "n") + 1) + 0.1:.2f}, '
            f'fontsize=9];')

    def write(self, path):
        bottom = self.y - STEP * 0.8
        head = []
        for x, label, fill in self.heads:
            self.n += 1
            h = f"h{self.n}"
            head.append(f'    {h} [pos="{x:.2f},0.35!", shape=box, '
                        f'style="rounded,filled", fillcolor="{fill}", '
                        f'label="{label}", width=1.3, height=0.42, '
                        f'fontsize=11];')
            top = self._pt(x, 0.14)
            end = self._pt(x, bottom)
            self.lines.append(f'    {top} -> {end} [arrowhead=none, '
                              'style=dashed, color="#999999"];')
        out = [
            f"// {self.comment}",
            "// Generated by sequences.py (do not edit by hand). Time runs",
            "// downwards and is not to scale.",
            "//",
            "// SPDX-License-Identifier: Apache-2.0",
            "",
            f"digraph {self.name} {{",
            '    graph [layout=neato, splines=false, overlap=true, '
            'fontname="Helvetica", outputorder=edgesfirst];',
            '    node  [shape=point, width=0.01, height=0.01, label="", '
            'fontname="Helvetica"];',
            '    edge  [arrowsize=0.7, penwidth=1.3];',
            "",
            *head,
            *self.lines,
            "}",
            "",
        ]
        path.parent.mkdir(exist_ok=True)
        path.write_text("\n".join(out), encoding="utf-8")
        print(f"wrote {path}")


def transactions():
    s = Seq("transactions", "Host", "Device", comment="The three kinds of "
            "transaction a full-speed serial port uses.")
    s.title("SETUP transaction")
    s.msg("l", "SETUP token")
    s.msg("l", "DATA0, 8-byte request")
    s.msg("r", "ACK", note="always ACK; never NAK or STALL")
    s.title("OUT transaction")
    s.msg("l", "OUT token")
    s.msg("l", "DATA0 or DATA1")
    s.msg("r", "ACK, NAK or STALL", note="ACK: taken; NAK: no room yet;\\n"
          "STALL: endpoint halted")
    s.title("IN transaction")
    s.msg("l", "IN token")
    s.msg("r", "DATA0 or DATA1, or NAK or STALL",
          note="NAK: no data ready")
    s.msg("l", "ACK", note="only after a data packet")
    s.write(HERE / "transactions" / "transactions.dot")


def retry():
    s = Seq("retry", "Host", "Device", comment="A lost ACK and the "
            "DATA0/DATA1 sequence bit; a missing reply counted as an error.")
    s.title("Lost ACK: the copy is recognised")
    s.msg("l", "OUT token")
    s.msg("l", "DATA1", note="device expects DATA1: stores it,\\n"
          "now expects DATA0")
    s.msg("r", "ACK", lost=True, note="ACK lost on the way")
    s.msg("l", "OUT token", note="host repeats the transaction")
    s.msg("l", "DATA1", note="DATA1 again: a copy, not stored twice")
    s.msg("r", "ACK")
    s.title("Packet with an error: no reply")
    s.msg("l", "IN token (bad CRC)", colour="#c0392b")
    s.note("device sends nothing; the host\\ncounts an error and retries")
    s.note("after three errors in a row\\nthe host gives up the transfer")
    s.write(HERE / "transactions" / "retry.dot")


def enumeration():
    s = Seq("enumeration", "Host", "Device", xn=6.9, comment="Enumeration "
            "of a full-speed device, with the time limits of USB 2.0.")
    s.note("VBUS valid")
    s.action("r", "D+ pull-up on within\\n100 ms (TSIGATT)")
    s.action("l", "wait at least\\n100 ms (TATTDB)")
    s.msg("l", "reset: SE0 for at least 10 ms", note="TDRST")
    s.action("l", "10 ms recovery\\n(TRSTRCY)")
    s.msg("l", "GET_DESCRIPTOR (device), address 0")
    s.msg("r", "first bytes: endpoint 0 packet size")
    s.msg("l", "SET_ADDRESS")
    s.msg("r", "status", note="complete within 50 ms;\\nnew address 2 ms "
          "later")
    s.msg("l", "GET_DESCRIPTOR, full", note="device, configuration and\\n"
          "string descriptors")
    s.msg("r", "descriptors", note="each data packet within 500 ms")
    s.msg("l", "SET_CONFIGURATION")
    s.msg("r", "status", note="the other endpoints now work")
    s.write(HERE / "transactions" / "enumeration.dot")


def dr_swap():
    s = Seq("dr_swap", "evampire\\n(source, DFP)", "Laptop\\n(sink, UFP)",
            fill=("#fbe5d6", "#dbe8f5"), comment="Data role swap with "
            "evampire as source: the data roles change, the power roles do "
            "not.")
    s.action("l", "pull-up off;\\nD+ and D− undriven")
    s.msg("l", "DR_Swap")
    s.msg("r", "GoodCRC")
    s.msg("r", "Accept", note="or Reject or Wait")
    s.msg("l", "GoodCRC")
    s.action("l", "now UFP: pull-up on\\nwhen VBUS present", gap=1.1)
    s.action("r", "now DFP: USB host", gap=0)
    s.note("unchanged: VBUS, Rp and Rd, VCONN", gap=1.2)
    s.note("on Reject: evampire stays DFP,\\nD+ and D− undriven, pull-up off")
    s.write(HERE / "usb-pd-roles" / "dr-swap.dot")


def control_transfer():
    s = Seq("control_transfer", "Host", "Device", comment="Stages of a "
            "control transfer that reads data, such as GET_DESCRIPTOR.")
    s.title("Setup stage")
    s.msg("l", "SETUP, DATA0 (8-byte request)")
    s.msg("r", "ACK")
    s.title("Data stage: IN transactions")
    s.msg("l", "IN")
    s.msg("r", "DATA1")
    s.msg("l", "ACK", note="repeated, DATA0/DATA1\\nalternating, until all is sent")
    s.title("Status stage: opposite direction")
    s.msg("l", "OUT, zero-length DATA1")
    s.msg("r", "ACK", note="a request that writes data\\nends with an IN status stage")
    s.write(HERE / "transactions" / "control-transfer.dot")


if __name__ == "__main__":
    transactions()
    retry()
    enumeration()
    dr_swap()
    control_transfer()
