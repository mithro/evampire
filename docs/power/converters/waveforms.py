"""Write buck-waveforms.dot: idealised buck converter waveforms.

The traces are drawn as polylines of pinned points on a fixed grid so that
graphviz (neato) renders them at a known size. Run with:

    uv run docs/power/converters/waveforms.py

SPDX-License-Identifier: Apache-2.0
"""

import pathlib

D = 0.25            # duty cycle of the worked example
DEAD = 0.035        # dead time as a fraction of the period, drawn enlarged
PERIODS = 2
X0, X1 = 1.55, 7.2  # plot area, inches
W = (X1 - X0) / PERIODS
H = 0.45            # height of one trace, inches

# Baseline (y) of each trace, top to bottom.
TRACES = [
    ("g1", "S1 gate", 3.6),
    ("g2", "S2 gate", 2.85),
    ("vsw", "Switch node\nvoltage", 2.1),
    ("il", "Inductor\ncurrent", 0.6),
]

lines = []
nodes = []
edges = []
count = 0


def pt(x, y):
    global count
    count += 1
    name = f"p{count}"
    nodes.append(f'    {name} [pos="{x:.3f},{y:.3f}!"];')
    return name


def poly(points, attrs=""):
    names = [pt(x, y) for x, y in points]
    for a, b in zip(names, names[1:]):
        edges.append(f"    {a} -- {b}{attrs};")


def square(y0, segments):
    """segments: list of (t_start, t_end) high intervals, t in periods."""
    pts = [(X0, y0)]
    for t0, t1 in segments:
        xa, xb = X0 + t0 * W, X0 + t1 * W
        pts += [(xa, y0), (xa, y0 + H), (xb, y0 + H), (xb, y0)]
    pts.append((X1, y0))
    poly(pts)


on = [(k, k + D) for k in range(PERIODS)]
off = [(k + D + DEAD, k + 1 - DEAD) for k in range(PERIODS)]
square(TRACES[0][2], on)
square(TRACES[1][2], off)
square(TRACES[2][2], on)

# Inductor current: rises during the on time, falls during the off time.
y0 = TRACES[3][2]
lo, hi = y0 + 0.15, y0 + 0.95
pts = []
for k in range(PERIODS):
    pts += [(X0 + k * W, lo), (X0 + (k + D) * W, hi)]
pts.append((X1, lo))
poly(pts)
# Average current, dashed.
mid = (lo + hi) / 2
poly([(X0, mid), (X1, mid)], ' [style=dashed, penwidth=1]')

labels = []
for key, text, y in TRACES:
    ymid = y + (0.55 if key == "il" else H / 2)
    labels.append(
        f'    l_{key} [pos="0.7,{ymid:.3f}!", shape=plaintext, label="{text}", '
        f'width=1.3, height=0.4];')
labels.append(
    f'    l_avg [pos="{X1 + 0.0:.3f},{mid + 0.17:.3f}!", shape=plaintext, '
    f'label="average = Iout", width=1.2, height=0.2, fontsize=10];')
labels.append(
    f'    l_pk [pos="{X0 + D * W:.3f},{hi + 0.15:.3f}!", shape=plaintext, '
    f'label="peak", width=0.5, height=0.2, fontsize=10];')
labels.append(
    f'    l_vin [pos="{X0 + D * W / 2:.3f},{TRACES[2][2] + H + 0.15:.3f}!", '
    f'shape=plaintext, label="Vin", width=0.5, height=0.2, fontsize=10];')
labels.append(
    f'    l_ton [pos="{X0 + D * W / 2:.3f},{TRACES[0][2] + H + 0.15:.3f}!", '
    f'shape=plaintext, label="D × T", width=0.6, height=0.2, fontsize=10];')
labels.append(
    f'    l_t [pos="{X0 + W / 2:.3f},{0.25:.3f}!", shape=plaintext, '
    f'label="one period T", width=1.2, height=0.2, fontsize=10];')
labels.append(
    f'    l_dt [pos="{X0 + (D + 1 - DEAD) * W / 2 + 0.0:.3f},'
    f'{TRACES[1][2] + H + 0.15:.3f}!", shape=plaintext, '
    f'label="S2 on (gaps at each end are the dead time)", width=3.0, '
    f'height=0.2, fontsize=10];')
# Period marker line.
period = [pt(X0, 0.12), pt(X0 + W, 0.12)]
edges.append(f"    {period[0]} -- {period[1]} [penwidth=1, dir=both, arrowsize=0.5];")

out = f"""// Idealised waveforms of a synchronous buck converter, generated by
// waveforms.py (do not edit by hand). Duty cycle {D}; the dead time is drawn
// larger than in a real converter so that it is visible.
//
// SPDX-License-Identifier: Apache-2.0

graph buck_waveforms {{
    graph [layout=neato, splines=false, overlap=true, fontname="Helvetica",
           size="7.4,5"];
    node  [fontname="Helvetica", fontsize=11];
    edge  [penwidth=1.6];

{chr(10).join(labels)}

    node  [shape=point, width=0.01, height=0.01, label=""];
{chr(10).join(nodes)}

{chr(10).join(edges)}
}}
"""
path = pathlib.Path(__file__).with_name("buck-waveforms.dot")
path.write_text(out)
print(f"wrote {path}")
